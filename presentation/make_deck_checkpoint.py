def slide_texts(s: dict) -> list[str]:
    out = [s.get("title", ""), s.get("sub", ""), s.get("bottom", ""), s.get("hyp", ""), s.get("how", ""),
           s.get("dec", ""), s.get("bar_title", ""), s.get("notes", "")]
    out += list(s.get("details", []))
    for pair in s.get("nums", []) + ([s["num"]] if s.get("num") else []):
        out += list(pair)
    for lab, v in s.get("bars", []):
        out += [lab, n(v, s.get("bar_fmt", 1))]
    return [t for t in out if t]


def check(M: list[dict], A: list[dict]) -> list[str]:
    import importlib.util
    spec = importlib.util.spec_from_file_location("tcdn", ROOT / "tests" / "test_case_docs_numbers.py")
    t = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(t)
    allowed = set(t.WHITELIST) | {str(y) for y in range(2018, 2027)} | {"4"}  # годы ссылок; 4 статуса постановки
    for v in mdc.USED.values():
        allowed |= t._variants(v)
    errs = []
    for i, s in enumerate(M + A, 1):
        txt = "\n".join(slide_texts(s))
        txt = re.sub(r"(\d) (\d{3})", r"\1\2", txt)
        txt = re.sub(r"\bSentinel-2\b|\bS2\b|\bL2A\b|\bAP50\b|\bB1\b|\bM[12]\b|\bv2\b|\bP3\b|\bER604\b|\b30SXE\b|\bERA5\b",
                     " ", txt)
        for tok in t._numbers(txt):
            if tok not in allowed:
                errs.append(f"слайд {i}: число без источника «{tok}»")
        low = txt.lower()
        for bad in FORBIDDEN:
            if bad.lower() in low:
                errs.append(f"слайд {i}: запрещённая формулировка «{bad}»")
        first = s.get("notes", "").split(". ")[0].rstrip(".")
        if s["kind"] in ("std", "bars", "img_wide", "app") and s.get("title"):
            if first[:25].lower() != s["title"][:25].lower():
                errs.append(f"слайд {i}: первая фраза заметок ≠ заголовок")
    for i, s in enumerate(M, 1):
        sec = words_s(s.get("notes", ""))
        if s["kind"] not in ("team", "final") and not 55 <= sec <= 95:
            errs.append(f"слайд {i}: заметки {sec} с (нужно 60–90)")
    return errs


def to_pdf(pptx: Path) -> Path | None:
    so = mdc._soffice()
    if not so:
        print("[deck_ckpt] LibreOffice не найден: PDF пропущен")
        return None
    prof = ROOT / "out" / "lo_profile_ckpt"
    subprocess.run([so, f"-env:UserInstallation=file:///{prof.as_posix()}", "--headless", "--convert-to", "pdf",
                    "--outdir", str(pptx.parent), str(pptx)], check=True, capture_output=True, timeout=600)
    pdf = pptx.with_suffix(".pdf")
    print(f"[deck_ckpt] PDF: {pdf.relative_to(ROOT)} ({pdf.stat().st_size // 1024} КБ)")
    return pdf


