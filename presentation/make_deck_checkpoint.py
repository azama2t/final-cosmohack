def prepare_images(shots_ok: bool) -> dict:
    """Производные картинки в presentation/img/ckpt: титул (затемнённая сцена), команда (из образца), вырезки."""
    from PIL import Image, ImageEnhance
    from pptx import Presentation

    CK.mkdir(parents=True, exist_ok=True)
    out: dict[str, Path] = {}

    def cover(src: Path, dst: Path, box=None, dark: float | None = None, size=(1920, 1080)):
        if not src.exists():
            return None
        im = Image.open(src).convert("RGB")
        if box:
            im = im.crop(box)
        if size:
            tw, th_ = size
            r = max(tw / im.width, th_ / im.height)
            im = im.resize((round(im.width * r), round(im.height * r)), Image.LANCZOS)
            x0, y0 = (im.width - tw) // 2, (im.height - th_) // 2
            im = im.crop((x0, y0, x0 + tw, y0 + th_))
        if dark:
            im = ImageEnhance.Brightness(im).enhance(dark)
        im.save(dst, quality=88)
        return dst

    # титул: снимок сцены с найденными полосами (без панелей интерфейса), затемнён
    out["title_bg"] = cover(IMG / "scene.jpg", CK / "title_bg.jpg", box=(700, 60, 1450, 1060), dark=0.42)
    # сцена с контурами зон (слайд «Зоны»)
    out["scene"] = cover(IMG / "scene.jpg", CK / "scene_zones.jpg", box=(640, 60, 1450, 1060), size=None)
    # команда — фото и имена из образца
    team = CK / "team.png"
    if not team.exists() and TEMPLATE.exists():
        tp = Presentation(TEMPLATE)
        for sh in tp.slides[1].shapes:
            if sh.shape_type == 13 and sh.width > 12_000_000:
                team.write_bytes(sh.image.blob)
                break
    # в образце заголовок «НАША КОМАНДА.» нарисован на самой картинке — берём полосу с фото и именами
    team_c = CK / "team_row.jpg"
    if team.exists():
        Image.open(team).convert("RGB").crop((90, 400, 1672, 905)).save(team_c, quality=90)
    out["team"] = team_c if team_c.exists() else None
    out["hard"] = ROOT / "docs" / "img" / "hard_background.jpg"
    out["ispra"] = ROOT / "docs" / "research" / "pairs" / "img" / "ispra_er604_20190916.png"
    out["funnel"] = ROOT / "docs" / "img" / "funnel.png"
    out["ladder"] = ROOT / "docs" / "img" / "units_ladder.png"
    out["adis_pair"] = ROOT / "docs" / "img" / "search_adis_pair.jpg"
    out["indep"] = ROOT / "docs" / "img" / "independent_adis_pairs.jpg"
    # интерфейс: до вехи 6 — прежние кадры presentation/img (make_shots.py), после — пересъёмка
    out["card"] = cover(IMG / "card.jpg", CK / "card.jpg", box=(1180, 40, 1920, 1080), size=None)
    out["photo"] = IMG / "photo.jpg"
    out["export"] = IMG / "export.jpg"
    out["earth"] = IMG / "earth.jpg"
    return {k: v for k, v in out.items() if v and Path(v).exists()}


