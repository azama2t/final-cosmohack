def build(slides: list[dict], imgs: dict, out: Path, total_main: int) -> None:
    from pptx import Presentation
    from pptx.chart.data import CategoryChartData  # noqa: F401
    from pptx.dml.color import RGBColor
    from pptx.enum.shapes import MSO_SHAPE
    from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
    from pptx.util import Emu, Inches, Pt

    rgb = lambda c: RGBColor(*c)  # noqa: E731
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    blank = prs.slide_layouts[6]

    def bg(slide, color):
        f = slide.background.fill
        f.solid()
        f.fore_color.rgb = rgb(color)

    def text(slide, x, y, w, h, paras, size=16, color=INK, bold=False, anchor=MSO_ANCHOR.TOP, align=PP_ALIGN.LEFT,
             space=4, fit=False):
        tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        tf = tb.text_frame
        tf.word_wrap = True
        tf.vertical_anchor = anchor
        tf.margin_left = tf.margin_right = Inches(0.02)
        tf.margin_top = tf.margin_bottom = Inches(0.02)
        for i, p in enumerate(paras if isinstance(paras, list) else [paras]):
            para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            para.alignment = align
            para.space_after = Pt(space)
            segs = p if isinstance(p, list) else [(p, {})]
            for seg, st in segs:
                r = para.add_run()
                r.text = seg
                r.font.name = FONT
                r.font.size = Pt(st.get("size", size))
                r.font.bold = st.get("bold", bold)
                r.font.color.rgb = rgb(st.get("color", color))
        return tb

    def picture(slide, path, x, y, w, h, align="center", border=True):
        from PIL import Image
        im = Image.open(path)
        r = min(w / im.width, h / im.height)
        pw, ph = im.width * r, im.height * r
        px = x + (w - pw) / 2 if align == "center" else x
        py = y + (h - ph) / 2
        pic = slide.shapes.add_picture(str(path), Inches(px), Inches(py), Inches(pw), Inches(ph))
        if border:
            pic.line.color.rgb = rgb((0xDD, 0xDF, 0xE3))
            pic.line.width = Pt(0.75)
        return pic

    def rule(slide, x, y, w, color=RULE):
        ln = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Emu(19050))
        ln.fill.solid()
        ln.fill.fore_color.rgb = rgb(color)
        ln.line.fill.background()

    def title(slide, t, color=INK, size=None):
        size = size or (32 if len(t) <= 60 else 28 if len(t) <= 100 else 25)
        text(slide, 0.71, 0.42, 11.9, 1.35, t, size=size, bold=True, color=color, anchor=MSO_ANCHOR.TOP)

    def pageno(slide, i, tot, color=LIGHT):
        text(slide, 11.6, 6.95, 1.1, 0.3, f"{i:02d} / {tot:02d}", size=11, color=color, align=PP_ALIGN.RIGHT)

    def bignum(slide, x, y, w, val, cap, size=66, cap_size=16, color=ORANGE, cap_color=GRAY):
        size = size if len(val) <= 6 else max(36, int(size * 6.5 / len(val)))
        text(slide, x, y, w, size / 72 * 1.25, val, size=size, bold=True, color=color)
        text(slide, x + 0.03, y + size / 72 * 1.3, w, 0.9, cap, size=cap_size, color=cap_color)

    def bars(slide, x, y, w, h, items, fmt, head=None, lower_better=False):
        if head:
            text(slide, x, y, w, 0.35, head, size=14, color=GRAY)
            y += 0.45
            h -= 0.45
        vmax = max(v for _, v in items if v is not None) or 1
        row = h / len(items)
        lab_w = 2.3
        for j, (lab, v) in enumerate(items):
            yy = y + j * row
            text(slide, x, yy + row * 0.18, lab_w - 0.1, row * 0.64, lab, size=15, color=INK if j == 0 else GRAY,
                 bold=(j == 0), anchor=MSO_ANCHOR.MIDDLE)
            bw = (w - lab_w - 1.1) * (v or 0) / vmax
            b = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x + lab_w), Inches(yy + row * 0.22),
                                       Inches(max(bw, 0.03)), Inches(row * 0.56))
            b.fill.solid()
            b.fill.fore_color.rgb = rgb(ORANGE if j == 0 else BAR_GRAY)
            b.line.fill.background()
            text(slide, x + lab_w + bw + 0.1, yy + row * 0.18, 1.0, row * 0.64, n(v, fmt), size=16,
                 color=ORANGE if j == 0 else GRAY, bold=True, anchor=MSO_ANCHOR.MIDDLE)

    for i, s in enumerate(slides, 1):
        sl = prs.slides.add_slide(blank)
        kind = s["kind"]
        if kind == "title":
            bg(sl, DARK)
            if "title_bg" in imgs:
                sl.shapes.add_picture(str(imgs["title_bg"]), 0, 0, prs.slide_width, prs.slide_height)
            text(sl, 0.91, 1.55, 11.5, 2.4, s["title"], size=38, bold=True, color=(0xFF, 0xFF, 0xFF))
            text(sl, 0.91, 4.45, 11.0, 0.8, s["sub"], size=22, color=(0xE4, 0xE6, 0xEA))
            text(sl, 0.91, 6.40, 11.0, 0.4, s["names"], size=15, color=DARK_TX)
        elif kind == "team":
            bg(sl, BG)
            text(sl, 0.71, 0.42, 11.9, 0.8, s["title"], size=36, bold=True)
            if "team" in imgs:
                picture(sl, imgs["team"], 0.5, 1.6, 12.3, 4.6, border=False)
            text(sl, 0.71, 6.35, 11.9, 0.4, "Кашин Г. · Закон М. · Панин М. · Ожигов Е. · Ведерников Ф.", size=15,
                 color=GRAY)
            pageno(sl, i, total_main)
        elif kind == "final":
            bg(sl, DARK)
            nums = s["nums"]
            cw = 11.9 / len(nums)
            for j, (v, c) in enumerate(nums):
                bignum(sl, 0.71 + j * cw, 2.3, cw - 0.2, v, c, size=80, cap_size=20, color=DARK_OR, cap_color=DARK_TX)
            text(sl, 0.71, 5.5, 11.9, 0.6, s["title"], size=26, bold=True, color=(0xFF, 0xFF, 0xFF),
                 align=PP_ALIGN.CENTER)
        elif kind == "divider":
            bg(sl, DARK)
            text(sl, 0.91, 2.4, 11.5, 1.2, s["title"], size=44, bold=True, color=(0xFF, 0xFF, 0xFF))
            text(sl, 0.91, 3.7, 11.0, 1.0, s["sub"], size=20, color=DARK_TX)
            rule(sl, 0.91, 3.55, 3.0, DARK_OR)
        elif kind == "app":
            bg(sl, BG)
            title(sl, s["title"])
            has_img = s.get("img") in imgs
            blocks = [("Гипотеза", s["hyp"]), ("Как проверили", s["how"]), ("Решение", s["dec"])]
            if has_img:  # слева число и три блока, справа картинка
                yy = 1.9
                if s.get("num"):
                    bignum(sl, 0.71, yy, 5.6, s["num"][0], s["num"][1], size=54, cap_size=14)
                    yy = 3.55
                step = (6.75 - yy) / 3
                for lab, body in blocks:
                    text(sl, 0.71, yy, 5.6, 0.28, lab.upper(), size=11, bold=True, color=ORANGE)
                    text(sl, 0.71, yy + 0.27, 5.6, step - 0.3, body[:1].upper() + body[1:], size=13, color=INK)
                    yy += step
                picture(sl, imgs[s["img"]], 6.6, 1.95, 6.0, 4.6)
            else:
                if s.get("num"):
                    bignum(sl, 0.71, 1.95, 4.3, s["num"][0], s["num"][1], size=72, cap_size=16)
                rx = 5.4 if s.get("num") else 0.71
                yy = 1.95
                for lab, body in blocks:
                    text(sl, rx, yy, 12.62 - rx, 0.3, lab.upper(), size=12, bold=True, color=ORANGE)
                    text(sl, rx, yy + 0.3, 12.62 - rx, 1.1, body[:1].upper() + body[1:], size=15, color=INK)
                    yy += 1.45
            text(sl, 0.71, 6.95, 6, 0.3, "Приложение · Исследование", size=11, color=LIGHT)
            pageno(sl, i, len(slides))
        else:  # std / bars / img_wide
            bg(sl, BG)
            title(sl, s["title"])
            nums = s.get("nums", [])
            img = imgs.get(s.get("img")) if s.get("img") else None
            bottom = s.get("bottom")
            y_bottom = 6.05
            if kind == "img_wide" and img:
                picture(sl, img, 0.71, 1.85, 11.9, 3.3)
                cw = 11.9 / max(1, len(nums))
                for j, (v, c) in enumerate(nums):
                    bignum(sl, 0.71 + j * cw * 0.6, 5.3, cw * 0.6 - 0.2, v, c, size=44, cap_size=14)
                if s.get("details"):
                    text(sl, 8.0, 5.45, 4.6, 1.2, s["details"], size=13, color=GRAY)
            elif kind == "bars":
                v, c = nums[0]
                bignum(sl, 0.71, 1.9, 4.4, v, c, size=72 if len(v) <= 6 else 60)
                bars(sl, 5.5, 1.95, 7.1, 3.1 if len(s["bars"]) > 2 else 2.2, s["bars"], s["bar_fmt"],
                     head=s.get("bar_title"))
                if s.get("details"):
                    text(sl, 5.5, 5.25 if len(s["bars"]) > 2 else 4.5, 7.1, 1.4, s["details"], size=14, color=GRAY)
            elif img:
                # слева крупные числа, справа картинка
                yy = 1.9
                for v, c in nums[:2]:
                    bignum(sl, 0.71, yy, 4.6, v, c, size=60 if len(v) <= 6 else 44, cap_size=15)
                    yy += 1.95
                picture(sl, img, 5.6, 1.9, 7.0, 3.95 if bottom else 4.6)
                if s.get("details"):
                    dy = max(yy - 0.1, 5.2) if not bottom else 5.95
                    if bottom:
                        text(sl, 5.6, 5.95, 7.0, 0.9, s["details"], size=12, color=GRAY, space=2)
                    else:
                        text(sl, 5.6, 6.6, 7.0, 0.6, s["details"], size=12, color=GRAY, space=2)
                if bottom:
                    text(sl, 0.71, 5.85, 4.7, 1.0, bottom, size=15, bold=True, color=INK)
                bottom = None
            else:
                cw = 11.9 / max(1, len(nums))
                for j, (v, c) in enumerate(nums):
                    bignum(sl, 0.71 + j * cw, 1.95, cw - 0.3, v, c, size=72 if len(nums) < 3 else 60, cap_size=16)
                if s.get("details"):
                    text(sl, 0.71, 4.3, 11.9, 1.5, s["details"], size=15, color=GRAY)
            if bottom:
                rule(sl, 0.71, y_bottom - 0.12, 11.9)
                text(sl, 0.71, y_bottom, 11.9, 0.6, bottom, size=20, bold=True)
            pageno(sl, i, total_main if i <= total_main else len(slides))
        sl.notes_slide.notes_text_frame.text = s.get("notes", "")
    prs.save(out)


