# ----------------------------------------------------------------------------------------------- числа
class Numbers:
    """Обязательные числа — k из make_deck_case.load(); необязательные — opt(path) (нет → None и путь в WANTED)."""

    def __init__(self):
        mdc.MISSING.clear()
        mdc.USED.clear()
        self.k = mdc.load()
        self.src = mdc.Src(json.loads(mdc.FN.read_text(encoding="utf-8")), "final_numbers")

    def opt(self, path: str):
        if self.src.has(path):
            return self.src(path)
        if path not in WANTED:
            WANTED.append(path)
        return None

    def get(self, path: str):
        return self.src(path)


def n(x, d: int = 1) -> str:
    return mdc.num(x, d)


def th(x) -> str:
    """Целое с неразрывным узким пробелом тысяч: 21 444."""
    if x is None:
        return "—"
    s = str(int(x))
    out = ""
    while len(s) > 3:
        out = " " + s[-3:] + out
        s = s[:-3]
    return s + out


